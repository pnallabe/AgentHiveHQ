"""Copilot service — natural language narrative generation for credit decisions.

Story 3.5: POST /api/copilot/explain

Architecture:
  1. Try Google Gemini (gemini-2.0-flash) if GEMINI_API_KEY is configured.
  2. Try OpenAI gpt-4o-mini if OPENAI_API_KEY is configured (fallback).
  3. On failure or missing keys → return deterministic mock narrative.

The mock response passes the same schema validation as the LLM response
and contains only values sourced from the decision input (no hallucination).
"""
from __future__ import annotations

import logging
import os
from typing import Any

from app.core.config import settings
from app.shared import loan_portfolio

logger = logging.getLogger(__name__)

_DISCLAIMER = (
    "This explanation is generated by AI and is for informational purposes only. "
    "Credit decisions are made by our automated underwriting system based on the "
    "financial factors described below."
)


# ── Response schema (mirrored by FastAPI schemas.py) ─────────────────────────

class CopilotResponse:
    """Plain dataclass — converted to dict before returning in API router."""

    def __init__(
        self,
        narrative: str,
        risk_flags: list[str],
        recommendations: list[str],
        plain_english_apr: str,
    ) -> None:
        self.narrative = narrative
        self.risk_flags = risk_flags
        self.recommendations = recommendations
        self.plain_english_apr = plain_english_apr

    def to_dict(self) -> dict[str, Any]:
        return {
            "narrative":          self.narrative,
            "risk_flags":         self.risk_flags,
            "recommendations":    self.recommendations,
            "plain_english_apr":  self.plain_english_apr,
        }


# ── Service ───────────────────────────────────────────────────────────────────

class CopilotService:
    """Generates plain-language credit decision narratives."""

    async def explain(
        self,
        decision_response: dict[str, Any],
        applicant_context: str = "",
        portfolio_context: dict[str, Any] | None = None,
    ) -> CopilotResponse:
        """Generate a narrative for the given underwriting decision.

        Args:
            decision_response: Full ``UnderwritingResponse`` as a dict.
            applicant_context: Optional free-text context about the applicant.

        Returns:
            ``CopilotResponse`` — either LLM-generated or deterministic mock.
        """
        # Fetch portfolio benchmarks if not already provided by the caller
        if portfolio_context is None:
            try:
                portfolio_context = decision_response.get("portfolio_context") or await loan_portfolio.get_population_benchmarks()
            except Exception:
                portfolio_context = None

        gemini_key = getattr(settings, "GEMINI_API_KEY", None) or os.environ.get("GEMINI_API_KEY", "")
        if gemini_key:
            try:
                return await self._call_gemini(decision_response, applicant_context, gemini_key, portfolio_context)
            except Exception as exc:
                logger.warning(
                    "Gemini copilot call failed — trying OpenAI fallback",
                    extra={"error": str(exc), "copilot_source": "gemini_error"},
                )

        openai_key = getattr(settings, "OPENAI_API_KEY", None) or os.environ.get("OPENAI_API_KEY", "")
        if openai_key:
            try:
                return await self._call_openai(decision_response, applicant_context, openai_key, portfolio_context)
            except Exception as exc:
                logger.warning(
                    "OpenAI copilot call failed — falling back to mock",
                    extra={"error": str(exc), "copilot_source": "openai_error"},
                )

        logger.info("copilot_source=mock")
        return self._build_mock(decision_response)

    # ── Gemini path ───────────────────────────────────────────────────────────

    async def _call_gemini(
        self,
        dr: dict[str, Any],
        applicant_context: str,
        api_key: str,
        portfolio_context: dict[str, Any] | None = None,
    ) -> CopilotResponse:
        """Call gemini-2.0-flash via google-generativeai SDK."""
        import json
        import google.generativeai as genai  # pip install google-generativeai

        genai.configure(api_key=api_key)

        decision = dr.get("decision", "unknown")
        credit_limit = dr.get("credit_limit")
        apr = dr.get("apr")
        risk_segment = dr.get("risk_segment", "unknown")
        reason_codes = dr.get("reason_codes", [])
        confidence_score = dr.get("confidence_score", 0)

        reason_text = ", ".join(
            rc.get("description", rc.get("code", "")) if isinstance(rc, dict) else str(rc)
            for rc in reason_codes
        ) or "No specific adverse factors."

        credit_limit_str = "${:,.0f}".format(credit_limit) if credit_limit else "N/A"
        apr_str = f"{apr:.2f}%" if apr else "N/A"
        context_line = f"- Applicant Context: {applicant_context}" if applicant_context else ""

        # Build portfolio benchmark context block for the prompt
        portfolio_block = ""
        if portfolio_context:
            cs_bench = portfolio_context.get("credit_score") or (portfolio_context.get("population_benchmarks") or {}).get("credit_score", {})
            peer_default = portfolio_context.get("peer_default_rate")
            cs_pct = portfolio_context.get("credit_score_percentile", "")
            if cs_bench or peer_default:
                portfolio_block = (
                    f"\nFreddie Mac Market Benchmarks (15.9M loans, 2015–2024):\n"
                    f"- Population median credit score: {cs_bench.get('median', 'N/A')}\n"
                    + (f"- Peer 90-day default rate for this credit band: {peer_default:.2%}\n" if peer_default is not None else "")
                    + (f"- Applicant credit score percentile: {cs_pct}\n" if cs_pct else "")
                )

        prompt = f"""You are a credit analyst at a regulated consumer lending institution.
Explain this credit decision clearly, empathetically, and in FCRA-compliant language.
Never hallucinate numbers or facts not in the data below.

Credit Decision Summary:
- Decision: {decision.upper()}
- Risk Segment: {risk_segment}
- Credit Limit: {credit_limit_str}
- APR: {apr_str}
- Confidence: {confidence_score:.0%}
- Reason Factors: {reason_text}
{context_line}{portfolio_block}

Respond with ONLY valid JSON (no markdown) with exactly these keys:
{{
  "narrative": "exactly 3 sentences explaining the decision clearly and empathetically",
  "risk_flags": ["up to 3 specific risk factors from the data above"],
  "recommendations": ["up to 3 concrete actions the applicant can take"],
  "plain_english_apr": "For every $1,000 balance, you'd pay approximately $X.XX/month in interest"
}}"""

        model = genai.GenerativeModel(
            model_name="gemini-2.0-flash",
            generation_config=genai.GenerationConfig(
                temperature=0.3,
                max_output_tokens=500,
                response_mime_type="application/json",
            ),
        )

        # Gemini SDK is sync — run in thread to avoid blocking the event loop
        import asyncio
        loop = asyncio.get_event_loop()
        response = await loop.run_in_executor(
            None, lambda: model.generate_content(prompt)
        )

        data = json.loads(response.text)
        logger.info("copilot_source=gemini")
        return CopilotResponse(
            narrative=str(data.get("narrative", ""))[:600],
            risk_flags=list(data.get("risk_flags", []))[:3],
            recommendations=list(data.get("recommendations", []))[:3],
            plain_english_apr=str(data.get("plain_english_apr", self._apr_text(apr))),
        )

    # ── OpenAI path ───────────────────────────────────────────────────────────

    async def _call_openai(
        self,
        dr: dict[str, Any],
        applicant_context: str,
        api_key: str,
        portfolio_context: dict[str, Any] | None = None,
    ) -> CopilotResponse:
        """Call gpt-4o-mini with a structured system + user prompt."""
        import openai

        decision = dr.get("decision", "unknown")
        credit_limit = dr.get("credit_limit")
        apr = dr.get("apr")
        risk_segment = dr.get("risk_segment", "unknown")
        reason_codes = dr.get("reason_codes", [])
        confidence_score = dr.get("confidence_score", 0)

        reason_text = ", ".join(
            rc.get("description", rc.get("code", "")) if isinstance(rc, dict) else str(rc)
            for rc in reason_codes
        ) or "No specific adverse factors."

        # Portfolio benchmark supplement
        portfolio_block = ""
        if portfolio_context:
            cs_bench = portfolio_context.get("credit_score") or (portfolio_context.get("population_benchmarks") or {}).get("credit_score", {})
            peer_default = portfolio_context.get("peer_default_rate")
            cs_pct = portfolio_context.get("credit_score_percentile", "")
            if cs_bench or peer_default:
                portfolio_block = (
                    f"\nFreddie Mac Market Benchmarks (15.9M loans, 2015–2024):\n"
                    f"- Population median credit score: {cs_bench.get('median', 'N/A')}\n"
                    + (f"- Peer 90-day default rate for this credit band: {peer_default:.2%}\n" if peer_default is not None else "")
                    + (f"- Applicant credit score percentile: {cs_pct}\n" if cs_pct else "")
                )

        system_prompt = (
            "You are a credit analyst at a regulated consumer lending institution. "
            "You explain credit decisions to applicants in a clear, empathetic, and "
            "FCRA-compliant manner. Never hallucinate numbers or facts not present in "
            "the decision data provided. Keep your narrative to exactly 3 sentences. "
            "If the decision is a rejection, always include an actionable improvement path."
        )

        credit_limit_str2 = "${:,.0f}".format(credit_limit) if credit_limit else "N/A"
        apr_str2 = f"{apr:.2f}%" if apr else "N/A"
        context_line2 = f"- Applicant Context: {applicant_context}" if applicant_context else ""

        user_prompt = f"""Credit Decision Summary:
- Decision: {decision.upper()}
- Risk Segment: {risk_segment}
- Credit Limit: {credit_limit_str2}
- APR: {apr_str2}
- Confidence: {confidence_score:.0%}
- Reason Factors: {reason_text}
{context_line2}{portfolio_block}

Provide:
1. narrative: exactly 3 sentences explaining this decision clearly and empathetically
2. risk_flags: up to 3 specific risk factors from the data above (array of short strings)
3. recommendations: up to 3 concrete actions the applicant can take (array of short strings)
4. plain_english_apr: using the formula "For every $1,000 balance, you'd pay approximately ${monthly:.2f}/month in interest" (calculate from APR={apr or 0})

Respond in JSON with keys: narrative, risk_flags, recommendations, plain_english_apr"""

        client = openai.AsyncOpenAI(api_key=api_key, timeout=9.0)
        response = await client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user",   "content": user_prompt},
            ],
            temperature=0.3,
            max_tokens=500,
            response_format={"type": "json_object"},
        )

        import json
        content = response.choices[0].message.content or "{}"
        data = json.loads(content)

        logger.info("copilot_source=openai")
        return CopilotResponse(
            narrative=str(data.get("narrative", ""))[:600],
            risk_flags=list(data.get("risk_flags", []))[:3],
            recommendations=list(data.get("recommendations", []))[:3],
            plain_english_apr=str(data.get("plain_english_apr", self._apr_text(apr))),
        )

    # ── Mock / fallback ───────────────────────────────────────────────────────

    def _build_mock(self, dr: dict[str, Any]) -> CopilotResponse:
        """Build a deterministic, template-filled narrative from decision fields.

        All values are sourced directly from the decision response —
        no hallucination possible.
        """
        decision     = dr.get("decision", "unknown")
        credit_limit = dr.get("credit_limit")
        apr          = dr.get("apr")
        risk_segment = dr.get("risk_segment", "unknown")
        confidence   = dr.get("confidence_score", 0.5)
        reason_codes = dr.get("reason_codes", [])

        # ── Narrative (3 sentences max) ───────────────────────────────────────
        if decision == "approve":
            limit_str = f"${credit_limit:,.0f}" if credit_limit else "a credit limit"
            apr_str   = f"{apr:.2f}%" if apr else "the standard rate"
            narrative = (
                f"Your application has been approved with {limit_str} at {apr_str} APR "
                f"based on your overall financial profile. "
                f"Your risk segment is classified as {risk_segment.replace('-', ' ')}, "
                f"reflecting a confidence score of {confidence:.0%}. "
                f"Your account is ready for activation — please review your terms carefully."
            )
            risk_flags = [
                "Monitor credit utilisation — keep usage below 30% of your limit.",
                f"Your risk segment ({risk_segment.replace('-', ' ')}) may qualify for a rate reduction after 12 months of on-time payments.",
            ]
            recommendations = [
                "Set up autopay to avoid missed payments.",
                "Keep your credit utilisation below 30% to build credit score.",
                "Review your credit report annually at AnnualCreditReport.com.",
            ]

        elif decision == "review":
            reason_text = (
                reason_codes[0].get("description", "additional review required")
                if reason_codes and isinstance(reason_codes[0], dict)
                else "additional review is needed before a final decision can be made"
            )
            narrative = (
                f"Your application requires additional review before a final decision can be made. "
                f"This is because {reason_text.lower().rstrip('.')}. "
                f"A credit specialist will contact you within 2 business days with next steps."
            )
            risk_flags = [
                rc.get("description", rc.get("code", "")) if isinstance(rc, dict) else str(rc)
                for rc in reason_codes[:3]
            ]
            recommendations = [
                "Gather documentation of additional income sources if applicable.",
                "Consider providing a co-signer with established credit history.",
                "Contact our credit team to discuss your application directly.",
            ]

        else:  # reject
            reason_text = (
                reason_codes[0].get("description", "the risk factors in your application")
                if reason_codes and isinstance(reason_codes[0], dict)
                else "the risk factors in your application"
            )
            narrative = (
                f"After careful review, we are unable to approve your application at this time "
                f"due to {reason_text.lower().rstrip('.')}. "
                f"This decision is based solely on financial factors, not personal characteristics. "
                f"You have the right to request a free copy of your credit report within 60 days."
            )
            risk_flags = [
                rc.get("description", rc.get("code", "")) if isinstance(rc, dict) else str(rc)
                for rc in reason_codes[:3]
            ] or ["Credit profile does not meet current underwriting requirements."]
            recommendations = [
                "Request your free credit report at AnnualCreditReport.com and dispute any errors.",
                "Focus on increasing income stability over the next 6–12 months.",
                "Consider a secured credit card to establish or rebuild credit history.",
            ]

        return CopilotResponse(
            narrative=narrative.strip(),
            risk_flags=risk_flags[:3],
            recommendations=recommendations[:3],
            plain_english_apr=self._apr_text(apr),
        )

    @staticmethod
    def _apr_text(apr: float | None) -> str:
        """Compute the plain-English APR explainer string."""
        if not apr:
            return "No interest applies — this application was not approved for a credit line."
        monthly = round(apr / 12 * (1_000 / 100), 2)
        return f"For every $1,000 balance, you'd pay approximately ${monthly:.2f}/month in interest."
