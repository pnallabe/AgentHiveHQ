"""SQLAlchemy ORM models for AgentHive.

All primary keys are UUID v7-style (time-ordered) generated by the
database driver, ensuring global uniqueness with no integer sequences —
a critical requirement for fintech audit trails.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any, List, Optional

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    ForeignKey,
    Numeric,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


def _new_uuid() -> str:
    """Generate a new UUID4 string.  Used as the default for PK columns."""
    return str(uuid.uuid4())


def _utcnow() -> datetime:
    return datetime.now(tz=timezone.utc)


class DecisionRecord(Base):
    """Immutable record of a single underwriting decision.

    Never update rows in this table — append only.  If a correction is
    needed, create a new record and reference the original via audit log.
    """

    __tablename__ = "decisions"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=_new_uuid,
        comment="UUID4 decision identifier — links to audit_logs.decision_id",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=_utcnow,
        nullable=False,
        index=True,
        comment="UTC timestamp when the decision was produced",
    )

    # ── Applicant context ──────────────────────────────────────────────────
    applicant_ref: Mapped[Optional[str]] = mapped_column(
        String(128),
        nullable=True,
        comment="External applicant reference (optional, caller-supplied)",
    )
    input_payload: Mapped[dict] = mapped_column(
        JSON,
        nullable=False,
        comment="Raw request payload as submitted — never mutated post-write",
    )

    # ── Decision output ────────────────────────────────────────────────────
    decision: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        index=True,
        comment="approve | reject | review",
    )
    credit_limit: Mapped[Optional[float]] = mapped_column(
        Numeric(12, 2),
        nullable=True,
        comment="Approved credit limit in USD; NULL when rejected",
    )
    apr: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 2),
        nullable=True,
        comment="Annual percentage rate; NULL when rejected",
    )
    confidence_score: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 4),
        nullable=True,
        comment="Model confidence in [0,1]; 1 = maximally confident",
    )
    risk_segment: Mapped[Optional[str]] = mapped_column(
        String(32),
        nullable=True,
        comment="prime | near-prime | high-risk | thin-file",
    )
    reason_codes: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
        comment="FCRA §615 adverse action reason codes",
    )
    shap_values: Mapped[Optional[dict]] = mapped_column(
        JSON,
        nullable=True,
        comment="Feature-level SHAP contributions; NULL for rule-triggered decisions",
    )

    # ── Provenance ─────────────────────────────────────────────────────────
    model_version: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        comment="Artifact version string, e.g. '1.0.0' or 'demo-1.0.0'",
    )
    rules_triggered: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
        comment="Names of rules that evaluated to true (may be empty)",
    )
    demo_mode: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        index=True,
        comment="True when the decision was produced by a demo mock, not live inference",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    audit_logs: Mapped[List["AuditLog"]] = relationship(
        "AuditLog",
        back_populates="decision",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<DecisionRecord id={self.id} decision={self.decision}>"


class AuditLog(Base):
    """Append-only audit trail row linked to a DecisionRecord.

    Each significant event in the decision lifecycle appends a new row.
    Never update or delete audit rows (except cascade delete of demo records).
    """

    __tablename__ = "audit_logs"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=_new_uuid,
        comment="UUID4 audit log entry identifier",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=_utcnow,
        nullable=False,
        index=True,
    )

    # ── Linkage ────────────────────────────────────────────────────────────
    decision_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("decisions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Foreign key to decisions.id",
    )

    # ── Event descriptor ───────────────────────────────────────────────────
    event_type: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        comment="Controlled vocabulary: decision_made | rule_triggered | model_called | demo_served",
    )
    actor: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        default="system",
        comment="Who triggered the event — system, user ID, or service name",
    )
    metadata_: Mapped[dict] = mapped_column(
        "metadata",
        JSON,
        nullable=False,
        default=dict,
        comment="Arbitrary context dict — never used for decision logic",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    decision: Mapped["DecisionRecord"] = relationship(
        "DecisionRecord",
        back_populates="audit_logs",
    )

    def __repr__(self) -> str:
        return f"<AuditLog id={self.id} event={self.event_type} decision={self.decision_id}>"


# ── Analytics materialised-cache tables ──────────────────────────────────────
# These are NOT source-of-truth tables.  They are local caches written by the
# analytics aggregator on a 15-minute schedule so dashboard reads are fast.
# Canonical sources: PostgreSQL CC DB (card_accounts) + BigQuery (loan_applications).

class LoanRecord(Base):
    """Local materialised cache of origination records.

    Sourced from ``origination_5m.parquet`` (CC) and BigQuery ``credit_decisions``
    (loans).  On a cache miss or first run the aggregator populates from adapters.
    Never update rows — replace the snapshot entry for the account_ref instead.
    """

    __tablename__ = "loan_records"

    id: Mapped[str] = mapped_column(
        String(36), primary_key=True, default=_new_uuid,
        comment="UUID4 primary key",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, nullable=False,
        comment="Row creation timestamp (UTC)",
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=_utcnow, onupdate=_utcnow, nullable=False,
        comment="Last update timestamp (UTC)",
    )

    # ── Identifying attributes ─────────────────────────────────────────────
    product_type: Mapped[str] = mapped_column(
        String(32), nullable=False, index=True,
        comment="credit_card | mortgage",
    )
    decision_id: Mapped[Optional[str]] = mapped_column(
        String(36), nullable=True,
        comment="FK → decisions.id (nullable for mortgages)",
    )
    account_ref: Mapped[str] = mapped_column(
        String(128), nullable=False, index=True,
        comment="Internal account reference (hashed for PII)",
    )

    # ── Origination data ───────────────────────────────────────────────────
    origination_date: Mapped[Optional[datetime]] = mapped_column(
        DateTime(timezone=True), nullable=True,
        comment="Date the account was originated",
    )
    original_balance: Mapped[Optional[float]] = mapped_column(
        Numeric(14, 2), nullable=True,
        comment="Credit cards: credit limit. Mortgages: loan amount.",
    )
    original_ltv: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 4), nullable=True,
        comment="Loan-to-value at origination. Mortgages only; NULL for credit cards.",
    )
    original_term_months: Mapped[Optional[int]] = mapped_column(
        nullable=True,
        comment="Original term in months (12–360)",
    )
    origination_channel: Mapped[Optional[str]] = mapped_column(
        String(32), nullable=True,
        comment="digital | branch | broker",
    )
    interest_rate: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 4), nullable=True,
        comment="Annualised interest rate, e.g. 0.1999 = 19.99%",
    )
    risk_segment: Mapped[Optional[str]] = mapped_column(
        String(32), nullable=True, index=True,
        comment="prime | near_prime | high_risk | thin_file",
    )

    # ── Current balance snapshot ───────────────────────────────────────────
    current_balance: Mapped[Optional[float]] = mapped_column(
        Numeric(14, 2), nullable=True,
        comment="Outstanding balance — updated monthly by settlement job",
    )
    days_past_due: Mapped[Optional[int]] = mapped_column(
        nullable=True,
        comment="Current DPD bucket: 0 | 30 | 60 | 90 | 120+",
    )
    is_npl: Mapped[Optional[bool]] = mapped_column(
        Boolean, nullable=True,
        comment="Non-performing: DPD >= 90",
    )
    is_charged_off: Mapped[Optional[bool]] = mapped_column(
        Boolean, nullable=True,
        comment="Account has been charged off",
    )

    # ── Revenue attribution ────────────────────────────────────────────────
    interest_income_mtd: Mapped[Optional[float]] = mapped_column(
        Numeric(14, 2), nullable=True,
        comment="Month-to-date interest income for this account",
    )
    fee_income_mtd: Mapped[Optional[float]] = mapped_column(
        Numeric(14, 2), nullable=True,
        comment="Month-to-date fee income for this account",
    )
    cost_of_funds_rate: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 4), nullable=True,
        comment="Internal FTP (funds transfer pricing) rate",
    )

    # ── Marketing / acquisition ────────────────────────────────────────────
    acquisition_cost: Mapped[Optional[float]] = mapped_column(
        Numeric(10, 2), nullable=True,
        comment="Customer acquisition cost at origination (CAC)",
    )
    acquisition_channel: Mapped[Optional[str]] = mapped_column(
        String(32), nullable=True,
        comment="organic | paid_search | affiliate | broker",
    )

    def __repr__(self) -> str:
        return f"<LoanRecord id={self.id} product={self.product_type} ref={self.account_ref}>"


