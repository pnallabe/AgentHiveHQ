"""SQLAlchemy ORM models for AgentHive.

All primary keys are UUID v7-style (time-ordered) generated by the
database driver, ensuring global uniqueness with no integer sequences —
a critical requirement for fintech audit trails.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import Any, List, Optional

from sqlalchemy import (
    JSON,
    Boolean,
    DateTime,
    ForeignKey,
    Numeric,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID as PG_UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


def _new_uuid() -> str:
    """Generate a new UUID4 string.  Used as the default for PK columns."""
    return str(uuid.uuid4())


def _utcnow() -> datetime:
    return datetime.now(tz=timezone.utc)


class DecisionRecord(Base):
    """Immutable record of a single underwriting decision.

    Never update rows in this table — append only.  If a correction is
    needed, create a new record and reference the original via audit log.
    """

    __tablename__ = "decisions"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=_new_uuid,
        comment="UUID4 decision identifier — links to audit_logs.decision_id",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=_utcnow,
        nullable=False,
        index=True,
        comment="UTC timestamp when the decision was produced",
    )

    # ── Applicant context ──────────────────────────────────────────────────
    applicant_ref: Mapped[Optional[str]] = mapped_column(
        String(128),
        nullable=True,
        comment="External applicant reference (optional, caller-supplied)",
    )
    input_payload: Mapped[dict] = mapped_column(
        JSON,
        nullable=False,
        comment="Raw request payload as submitted — never mutated post-write",
    )

    # ── Decision output ────────────────────────────────────────────────────
    decision: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
        index=True,
        comment="approve | reject | review",
    )
    credit_limit: Mapped[Optional[float]] = mapped_column(
        Numeric(12, 2),
        nullable=True,
        comment="Approved credit limit in USD; NULL when rejected",
    )
    apr: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 2),
        nullable=True,
        comment="Annual percentage rate; NULL when rejected",
    )
    confidence_score: Mapped[Optional[float]] = mapped_column(
        Numeric(5, 4),
        nullable=True,
        comment="Model confidence in [0,1]; 1 = maximally confident",
    )
    risk_segment: Mapped[Optional[str]] = mapped_column(
        String(32),
        nullable=True,
        comment="prime | near-prime | high-risk | thin-file",
    )
    reason_codes: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
        comment="FCRA §615 adverse action reason codes",
    )
    shap_values: Mapped[Optional[dict]] = mapped_column(
        JSON,
        nullable=True,
        comment="Feature-level SHAP contributions; NULL for rule-triggered decisions",
    )

    # ── Provenance ─────────────────────────────────────────────────────────
    model_version: Mapped[str] = mapped_column(
        String(32),
        nullable=False,
        comment="Artifact version string, e.g. '1.0.0' or 'demo-1.0.0'",
    )
    rules_triggered: Mapped[list] = mapped_column(
        JSON,
        nullable=False,
        default=list,
        comment="Names of rules that evaluated to true (may be empty)",
    )
    demo_mode: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        index=True,
        comment="True when the decision was produced by a demo mock, not live inference",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    audit_logs: Mapped[List["AuditLog"]] = relationship(
        "AuditLog",
        back_populates="decision",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<DecisionRecord id={self.id} decision={self.decision}>"


class AuditLog(Base):
    """Append-only audit trail row linked to a DecisionRecord.

    Each significant event in the decision lifecycle appends a new row.
    Never update or delete audit rows (except cascade delete of demo records).
    """

    __tablename__ = "audit_logs"

    id: Mapped[str] = mapped_column(
        String(36),
        primary_key=True,
        default=_new_uuid,
        comment="UUID4 audit log entry identifier",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=_utcnow,
        nullable=False,
        index=True,
    )

    # ── Linkage ────────────────────────────────────────────────────────────
    decision_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("decisions.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
        comment="Foreign key to decisions.id",
    )

    # ── Event descriptor ───────────────────────────────────────────────────
    event_type: Mapped[str] = mapped_column(
        String(64),
        nullable=False,
        comment="Controlled vocabulary: decision_made | rule_triggered | model_called | demo_served",
    )
    actor: Mapped[str] = mapped_column(
        String(128),
        nullable=False,
        default="system",
        comment="Who triggered the event — system, user ID, or service name",
    )
    metadata_: Mapped[dict] = mapped_column(
        "metadata",
        JSON,
        nullable=False,
        default=dict,
        comment="Arbitrary context dict — never used for decision logic",
    )

    # ── Relationships ──────────────────────────────────────────────────────
    decision: Mapped["DecisionRecord"] = relationship(
        "DecisionRecord",
        back_populates="audit_logs",
    )

    def __repr__(self) -> str:
        return f"<AuditLog id={self.id} event={self.event_type} decision={self.decision_id}>"
